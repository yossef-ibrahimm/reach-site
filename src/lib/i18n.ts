const TABLES: Record<Lang, Record<TKey, string>> = { ar, en };

export type TVars = Readonly<Record<string, string | number>>;

/**
 * Look up a key and substitute `{name}` placeholders.
 * Unknown keys are impossible (typed), missing vars are left untouched.
 */
export function translate(lang: Lang, key: TKey, vars?: TVars): string {
  const template = TABLES[lang][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name];
    return value === undefined ? whole : String(value);
  });
}

/** All keys of a language — handy for tests and for the admin editor. */
export function keys(): readonly TKey[] {
  return Object.keys(ar) as TKey[];
}
